"""Write runs/s6_validation_index.md from S6 part A's run logs (run from this artifacts folder).

Each line cites the log line that carries the result, so the index can be checked against the logs.
"""
import pathlib
import re

RUNS = pathlib.Path("runs")
OUTCOME = re.compile(r"^(tests/\S.*?) (PASSED|FAILED|ERROR|SKIPPED|XFAIL|XPASS)\b")
SUMMARY = re.compile(r"(passed|failed)[^\n]* in [0-9.]+s")


def summary_line(name: str) -> str:
    """Return 'runs/<name>:N-N  <pytest summary>' for the last summary line of a log."""
    lines = (RUNS / name).read_text(encoding="utf-8", errors="replace").splitlines()
    for number in range(len(lines), 0, -1):
        if SUMMARY.search(lines[number - 1]):
            text = lines[number - 1].strip("= ").strip()
            return f"- runs/{name}:{number}-{number}  {text}"
    raise SystemExit(f"no pytest summary in {name}")


def shard_line(prefix: str, ids_name: str) -> str:
    """Return the outcome counts of a resumable-shard run over its id file."""
    wanted = [line.strip() for line in (RUNS / ids_name).read_text(encoding="utf-8").splitlines() if line.strip()]
    done = {}
    parts = sorted(RUNS.glob(prefix + "_part*.txt"))
    for log in parts:
        for line in log.read_text(encoding="utf-8", errors="replace").splitlines():
            match = OUTCOME.match(line)
            if match:
                done[match.group(1)] = match.group(2)
    missing = [test_id for test_id in wanted if test_id not in done]
    counts = {}
    for test_id in wanted:
        if test_id in done:
            counts[done[test_id]] = counts.get(done[test_id], 0) + 1
    return f"- {prefix}: {len(wanted)} ids ({ids_name}); outcomes {counts}; {len(parts)} part log(s); missing {len(missing)}"


out = ["# S6 part A validation index (generated by scripts/s6_validation_index.py from the run logs)", ""]
out += ["Red before the fix, on 0.2.8253 (the new and changed tests):",
        summary_line("s6_red_gil0.txt"), summary_line("s6_red_gil1.txt"), ""]
out += ["Green after the fix (the same tests):",
        summary_line("s6_green_gil0.txt"), summary_line("s6_green_gil1.txt"), ""]
out += ["Managed suites after the fix (unit, component and integration files of the managed stack):",
        summary_line("s6_managed_suites_gil0.txt"), summary_line("s6_managed_suites_gil1.txt"), ""]
out += ["Cache generation 22 (the schema-history integration test with its new row, run with the caching unit file; the",
        "unit file's 12 failures are the connected folder refusing its temp-dir deletes, not the change - the whole-tree",
        "run below passes it in a /tmp mirror):",
        summary_line("s6_cache_generation_gil0.txt"), summary_line("s6_cache_generation_gil1.txt"), ""]
out += ["Whole tree in a /tmp mirror of the working tree (src, tests, pyproject.toml, docs, .github, llm_support,",
        "benchmarks, release_docs, architecture_and_design, context_compass/system_docs, the root config files):",
        summary_line("s6_tree_unit_aether_spellbook_gil0.txt"), summary_line("s6_tree_unit_aether_spellbook_gil1.txt"),
        shard_line("s6_tree_unit_rest_gil0", "unit_rest_ids.txt"),
        "  (the 4 FAILED ran before the mirror held .readthedocs.yaml, codecov.yml and context_compass/system_docs;",
        "  re-run after they were added:)",
        summary_line("s6_tree_unit_rest_gil0_mirror_gaps_rerun.txt"),
        shard_line("s6_tree_unit_rest_gil1", "unit_rest_ids.txt"),
        shard_line("s6_tree_component_gil0", "component_ids.txt"),
        shard_line("s6_tree_component_gil1", "component_ids.txt"),
        shard_line("s6_tree_integration_gil0", "integration_ids.txt"),
        shard_line("s6_tree_integration_gil1", "integration_ids.txt"),
        shard_line("s6_tree_experimentation_gil0", "experimentation_ids.txt"),
        shard_line("s6_tree_experimentation_gil1", "experimentation_ids.txt"), ""]
out += ["Hosted CI and coverage: Not run (the owner's)."]
(RUNS / "s6_validation_index.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
